package main

import (
	"fmt"

	"github.com/sunquakes/jsonrpc4go"
)

func main() {
	c, _ := jsonrpc4go.NewClient("IntRpc", "http", "127.0.0.1:3232")
	api := NewIntRpcApiClient(c) // generated by rpcgen

	sum, err := api.Add(1, 6)
	fmt.Println(sum, err) // 7 <nil>

	res, err := api.Add2(2, 3)
	fmt.Println(res.C, err) // 5 <nil>
}
