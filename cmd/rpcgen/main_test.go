package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// sampleAPI declares an interface covering the supported method shapes.
const sampleAPI = `package demo

type UserInfo struct {
	Name string ` + "`json:\"name\"`" + `
}

type UserApi interface {
	GetUser(id int) (UserInfo, error)
	Ping() error
	Lookup(name string, limit int) ([]UserInfo, error)
	Reset(_ bool) error
	Fetch(int) (UserInfo, error)
	Sum(a, b int) (int, error)
}
`

// writeTemp writes content into a fresh temp directory and returns it.
func writeTemp(t *testing.T, name, content string) string {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
		t.Fatalf("write %s: %v", name, err)
	}
	return dir
}

func TestRunGeneratesClient(t *testing.T) {
	dir := writeTemp(t, "api.go", sampleAPI)
	o := options{dir: dir, iface: "UserApi", service: "IntRpc"}
	var buf bytes.Buffer
	if err := run(o, &buf); err != nil {
		t.Fatalf("run: %v", err)
	}
	src := buf.String()
	checks := []string{
		"// Code generated by rpcgen. DO NOT EDIT.",
		"package demo",
		`"github.com/sunquakes/jsonrpc4go"`,
		`"github.com/sunquakes/jsonrpc4go/client"`,
		"type UserApiClient struct",
		"func NewUserApiClient(c client.Client) *UserApiClient",
		"func (p *UserApiClient) Client() client.Client",
		`func (p *UserApiClient) GetUser(id int) (UserInfo, error) {`,
		`return jsonrpc4go.Call[UserInfo](p.c, "GetUser", id)`,
		"func (p *UserApiClient) Ping() error {",
		`_, err := jsonrpc4go.Call[any](p.c, "Ping")`,
		"func (p *UserApiClient) Lookup(name string, limit int) ([]UserInfo, error) {",
		`return jsonrpc4go.Call[[]UserInfo](p.c, "Lookup", name, limit)`,
		"func (p *UserApiClient) Reset(a0 bool) error {",
		"func (p *UserApiClient) Fetch(a0 int) (UserInfo, error) {",
		`return jsonrpc4go.Call[UserInfo](p.c, "Fetch", a0)`,
		"func (p *UserApiClient) Sum(a, b int) (int, error) {",
		`return jsonrpc4go.Call[int](p.c, "Sum", a, b)`,
		"var _ UserApi = (*UserApiClient)(nil)",
	}
	for _, want := range checks {
		if !strings.Contains(src, want) {
			t.Errorf("generated source missing %q\n%s", want, src)
		}
	}
}

func TestRunWritesFileAndOverrides(t *testing.T) {
	dir := writeTemp(t, "api.go", sampleAPI)
	out := filepath.Join(dir, "api_rpc.go")
	o := options{dir: dir, iface: "UserApi", name: "TypedUser", service: "Svc", pkg: "demov2", out: out}
	if err := run(o, os.Stdout); err != nil {
		t.Fatalf("run: %v", err)
	}
	data, err := os.ReadFile(out)
	if err != nil {
		t.Fatalf("read output: %v", err)
	}
	src := string(data)
	for _, want := range []string{
		"package demov2",
		"type TypedUser struct",
		"func NewTypedUser(c client.Client) *TypedUser",
		`// GetUser calls "Svc/GetUser".`,
		"var _ UserApi = (*TypedUser)(nil)",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("generated source missing %q\n%s", want, src)
		}
	}
}

func TestRunDefaults(t *testing.T) {
	dir := writeTemp(t, "api.go", sampleAPI)
	var buf bytes.Buffer
	// The service prefix defaults to the interface name and the package to
	// the source package.
	if err := run(options{dir: dir, iface: "UserApi"}, &buf); err != nil {
		t.Fatalf("run: %v", err)
	}
	src := buf.String()
	if !strings.Contains(src, `"UserApi/GetUser"`) {
		t.Errorf("default service prefix missing\n%s", src)
	}
	if !strings.Contains(src, "type UserApiClient struct") {
		t.Errorf("default client name missing\n%s", src)
	}
}

func TestRunSingleFile(t *testing.T) {
	dir := t.TempDir()
	api := filepath.Join(dir, "api.go")
	if err := os.WriteFile(api, []byte(sampleAPI), 0o644); err != nil {
		t.Fatal(err)
	}
	// A second file that does not parse would break a directory scan, so
	// -file must be used for single-source generation.
	broken := filepath.Join(dir, "broken.go.txt")
	if err := os.WriteFile(broken, []byte("not go"), 0o644); err != nil {
		t.Fatal(err)
	}
	var buf bytes.Buffer
	if err := run(options{file: api, iface: "UserApi"}, &buf); err != nil {
		t.Fatalf("run: %v", err)
	}
	if !strings.Contains(buf.String(), "type UserApiClient struct") {
		t.Errorf("single file generation failed\n%s", buf.String())
	}
}

func TestRunRejectsUnsupportedMethods(t *testing.T) {
	tests := []struct {
		name   string
		source string
		want   string
	}{
		{
			name:   "variadic",
			source: "package p\ntype I interface {\n\tM(ids ...int) error\n}\n",
			want:   "variadic",
		},
		{
			name:   "no result",
			source: "package p\ntype I interface {\n\tM(a int)\n}\n",
			want:   "must return (value, error) or error",
		},
		{
			name:   "single value",
			source: "package p\ntype I interface {\n\tM(a int) int\n}\n",
			want:   "must return (value, error) or error",
		},
		{
			name:   "second result",
			source: "package p\ntype I interface {\n\tM(a int) (int, string)\n}\n",
			want:   "second result must be error",
		},
		{
			name:   "three results",
			source: "package p\ntype I interface {\n\tM(a int) (int, int, error)\n}\n",
			want:   "needs at most two",
		},
		{
			name:   "embedded",
			source: "package p\ntype Base interface {\n\tM() error\n}\ntype I interface {\n\tBase\n}\n",
			want:   "embedded interfaces are not supported",
		},
		{
			name:   "not an interface",
			source: "package p\ntype I struct{}\n",
			want:   "is not an interface",
		},
		{
			name:   "missing",
			source: sampleAPI,
			want:   `interface "Nope" not found`,
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			dir := writeTemp(t, "api.go", tc.source)
			iface := "I"
			if tc.name == "missing" {
				iface = "Nope"
			}
			var buf bytes.Buffer
			err := run(options{dir: dir, iface: iface}, &buf)
			if err == nil {
				t.Fatalf("expected an error, got:\n%s", buf.String())
			}
			if !strings.Contains(err.Error(), tc.want) {
				t.Errorf("error %q does not contain %q", err, tc.want)
			}
		})
	}
}

func TestRunRequiresInterface(t *testing.T) {
	if err := run(options{}, &bytes.Buffer{}); err == nil {
		t.Fatal("missing -iface was accepted")
	}
}
